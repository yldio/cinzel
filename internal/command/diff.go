// differ is a provider that can report what a parse would change.
//
// Narrower than provider.Provider on purpose. Diff belongs to the two real
// providers and to nothing else, and putting it on the interface would make
// every test double implement a method it has no answer for.
type differ interface {
	Diff(opts provider.ProviderOps) ([]provider.DiffResult, error)
}

func (cmd *Cli) diffCommand(p provider.Provider) *cli.Command {
	return &cli.Command{
		Name:  "diff",
		Usage: "Report what parse would change in the generated YAML, writing nothing",
		Action: func(ctx context.Context, c *cli.Command) error {
			d, ok := p.(differ)
			if !ok {
				return cannotRun(fmt.Errorf("%w: %s", errDiffUnsupported, p.GetProviderName()))
			}

			// Read as "parse": diff asks what parse would do, so it has to
			// run on the settings parse runs on. A separate "diff" section
			// would be a second place to keep the same answer.
			opts, warnings, err := toProviderOpts(c, p.GetProviderName(), "parse")
			if err != nil {
				return cannotRun(err)
			}

			for _, warning := range warnings {
				warnTo(c.Root().ErrWriter, warning)
			}

			results, err := d.Diff(opts)
			if err != nil {
				return cannotRun(err)
			}

			return cmd.reportDiff(results)
		},
		Flags: []cli.Flag{
			&cli.StringFlag{
				Name:    "file",
				Aliases: []string{"f"},
				Usage:   "Compare the YAML one HCL `FILE` would produce",
			},
			&cli.StringFlag{
				Name:    "directory",
				Aliases: []string{"d"},
				Usage:   "Compare the YAML the HCL files in `DIRECTORY` would produce",
			},
			&cli.BoolFlag{
				Name:    "recursive",
				Aliases: []string{"r"},
				Usage:   "Reads the directory recursively",
			},
			&cli.StringFlag{
				Name:  "output-directory",
				Usage: "Compare against the generated files in `DIRECTORY`",
			},
			&cli.BoolFlag{
				Name:  "yml",
				Usage: "Compare against .yml files instead of .yaml",
			},
		},
	}
}

// reportDiff writes a line for every path a parse would touch, then a
// summary, and returns the error that decides the exit code.
//
// Each file is named as it is judged, the way pin names an action it could
// not resolve: a summary saying "1 differs" with nothing naming the file
// leaves the reader hunting for it.
func (cmd *Cli) reportDiff(results []provider.DiffResult) error {
	differs, missing, stale := 0, 0, 0
	color := fsutil.UseColor(cmd.Writer)

	for _, result := range results {
		switch result.Status {
		case provider.DiffIdentical:
			continue
		case provider.DiffDiffers:
			differs++

			_, _ = fmt.Fprintf(cmd.Writer, "%s differs\n", result.Path)
			_, _ = fmt.Fprint(cmd.Writer, fsutil.Colorize(result.Unified, color))
		case provider.DiffMissing:
			missing++

			_, _ = fmt.Fprintf(cmd.Writer, "would create: %s\n", result.Path)
		case provider.DiffStale:
			stale++

			_, _ = fmt.Fprintf(cmd.Writer, "would delete: %s (generated by cinzel, no longer written)\n", result.Path)
		}
	}

	_, _ = fmt.Fprintf(
		cmd.Writer,
		"\nDiff summary: %d checked, %d differ, %d would be created, %d would be deleted\n",
		len(results), differs, missing, stale,
	)

	if differs+missing+stale > 0 {
		return fmt.Errorf("%w: %d of %d", ErrDiffFound, differs+missing+stale, len(results))
	}

	return nil
}
