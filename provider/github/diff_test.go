// diffSetUp writes one workflow's HCL and parses it, so the output directory
// holds exactly what the HCL produces. Every case below starts from a tree a
// diff should call clean.
func diffSetUp(t *testing.T) (hclDir string, outDir string) {
	t.Helper()

	tmp := t.TempDir()
	hclDir = filepath.Join(tmp, "hcl")
	outDir = filepath.Join(tmp, "out")

	if err := os.MkdirAll(hclDir, 0o750); err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(filepath.Join(hclDir, "ci.hcl"), []byte(workflowNamed("ci", "ci")), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := New().Parse(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir}); err != nil {
		t.Fatal(err)
	}

	return hclDir, outDir
}

// treeSnapshot records every file under dir and its contents, so a test can
// prove a diff changed nothing at all.
func treeSnapshot(t *testing.T, dir string) map[string]string {
	t.Helper()

	snapshot := map[string]string{}

	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}

		content, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}

		snapshot[path] = string(content)

		return nil
	})
	if err != nil {
		t.Fatal(err)
	}

	return snapshot
}

func statusOf(t *testing.T, results []provider.DiffResult, path string) provider.DiffStatus {
	t.Helper()

	for _, result := range results {
		if filepath.Base(result.Path) == path {
			return result.Status
		}
	}

	t.Fatalf("no result for %s in %v", path, results)

	return provider.DiffIdentical
}

func TestDiffReportsWhatParseWouldChange(t *testing.T) {
	t.Run("a tree parse just wrote is identical", func(t *testing.T) {
		hclDir, outDir := diffSetUp(t)

		results, err := New().Diff(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir})
		if err != nil {
			t.Fatal(err)
		}

		if provider.Changed(results) {
			t.Errorf("Diff() = %v, want nothing to do", results)
		}
	})

	t.Run("a hand-edited file differs", func(t *testing.T) {
		hclDir, outDir := diffSetUp(t)

		edited := filepath.Join(outDir, "ci.yaml")

		content, err := os.ReadFile(edited)
		if err != nil {
			t.Fatal(err)
		}

		changed := strings.Replace(string(content), "ubuntu-latest", "ubuntu-24.04", 1)

		if err := os.WriteFile(edited, []byte(changed), 0o644); err != nil {
			t.Fatal(err)
		}

		results, err := New().Diff(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir})
		if err != nil {
			t.Fatal(err)
		}

		if got := statusOf(t, results, "ci.yaml"); got != provider.DiffDiffers {
			t.Errorf("status = %v, want DiffDiffers", got)
		}

		for _, result := range results {
			if result.Status == provider.DiffDiffers && !strings.Contains(result.Unified, "ubuntu-24.04") {
				t.Errorf("the diff does not name the edited line:\n%s", result.Unified)
			}
		}
	})

	t.Run("a deleted file would be created", func(t *testing.T) {
		hclDir, outDir := diffSetUp(t)

		if err := os.Remove(filepath.Join(outDir, "ci.yaml")); err != nil {
			t.Fatal(err)
		}

		results, err := New().Diff(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir})
		if err != nil {
			t.Fatal(err)
		}

		if got := statusOf(t, results, "ci.yaml"); got != provider.DiffMissing {
			t.Errorf("status = %v, want DiffMissing", got)
		}
	})

	// The case a directory comparison cannot judge. A renamed workflow leaves
	// its old output behind, and to "diff -ru" that is a file on one side and
	// not the other — the same shape as drift, which never clears.
	t.Run("an orphan would be deleted and a hand-written file is left alone", func(t *testing.T) {
		hclDir, outDir := diffSetUp(t)

		orphan := filepath.Join(outDir, "orphan.yaml")
		manual := filepath.Join(outDir, "manual.yaml")

		marked := "# generated-by: cinzel\n# cinzel-provider: github\nname: orphan\n"

		if err := os.WriteFile(orphan, []byte(marked), 0o644); err != nil {
			t.Fatal(err)
		}

		if err := os.WriteFile(manual, []byte("name: written by hand\n"), 0o644); err != nil {
			t.Fatal(err)
		}

		results, err := New().Diff(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir})
		if err != nil {
			t.Fatal(err)
		}

		if got := statusOf(t, results, "orphan.yaml"); got != provider.DiffStale {
			t.Errorf("status = %v, want DiffStale", got)
		}

		for _, result := range results {
			if filepath.Base(result.Path) == "manual.yaml" {
				t.Errorf("a hand-written file was reported: %v", result)
			}
		}
	})

	// Generated bytes are LF. A checkout on Windows converts them, and
	// without normalising, every file on that runner reads as changed.
	t.Run("CRLF on disk is not a difference", func(t *testing.T) {
		hclDir, outDir := diffSetUp(t)

		path := filepath.Join(outDir, "ci.yaml")

		content, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}

		crlf := strings.ReplaceAll(string(content), "\n", "\r\n")

		if err := os.WriteFile(path, []byte(crlf), 0o644); err != nil {
			t.Fatal(err)
		}

		results, err := New().Diff(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir})
		if err != nil {
			t.Fatal(err)
		}

		if provider.Changed(results) {
			t.Errorf("a CRLF checkout read as drift: %v", results)
		}
	})

	t.Run("a change inside a CRLF file still differs", func(t *testing.T) {
		hclDir, outDir := diffSetUp(t)

		path := filepath.Join(outDir, "ci.yaml")

		content, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}

		changed := strings.Replace(string(content), "ubuntu-latest", "ubuntu-24.04", 1)

		if err := os.WriteFile(path, []byte(strings.ReplaceAll(changed, "\n", "\r\n")), 0o644); err != nil {
			t.Fatal(err)
		}

		results, err := New().Diff(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir})
		if err != nil {
			t.Fatal(err)
		}

		if got := statusOf(t, results, "ci.yaml"); got != provider.DiffDiffers {
			t.Errorf("status = %v, want DiffDiffers", got)
		}
	})

	t.Run("it writes nothing, whatever it finds", func(t *testing.T) {
		hclDir, outDir := diffSetUp(t)

		if err := os.WriteFile(filepath.Join(outDir, "orphan.yaml"),
			[]byte("# generated-by: cinzel\n# cinzel-provider: github\nname: orphan\n"), 0o644); err != nil {
			t.Fatal(err)
		}

		if err := os.Remove(filepath.Join(outDir, "ci.yaml")); err != nil {
			t.Fatal(err)
		}

		before := treeSnapshot(t, outDir)

		if _, err := New().Diff(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir}); err != nil {
			t.Fatal(err)
		}

		after := treeSnapshot(t, outDir)

		if len(before) != len(after) {
			t.Fatalf("the tree went from %d files to %d", len(before), len(after))
		}

		for path, content := range before {
			if after[path] != content {
				t.Errorf("%s was written to", path)
			}
		}
	})
}

// A run narrowed with --file judges that file's outputs and leaves every other
// one alone, the same way a narrowed parse prunes only its own.
func TestDiffNarrowedToOneFileLeavesAnotherAlone(t *testing.T) {
	tmp := t.TempDir()
	hclDir := filepath.Join(tmp, "hcl")
	outDir := filepath.Join(tmp, "out")

	if err := os.MkdirAll(hclDir, 0o750); err != nil {
		t.Fatal(err)
	}

	for _, name := range []string{"ci", "cd"} {
		path := filepath.Join(hclDir, name+".hcl")
		if err := os.WriteFile(path, []byte(workflowNamed(name, name)), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	if err := New().Parse(provider.ProviderOps{Directory: hclDir, OutputDirectory: outDir}); err != nil {
		t.Fatal(err)
	}

	results, err := New().Diff(provider.ProviderOps{
		File:            filepath.Join(hclDir, "ci.hcl"),
		OutputDirectory: outDir,
	})
	if err != nil {
		t.Fatal(err)
	}

	if provider.Changed(results) {
		t.Errorf("a narrowed diff reported another file's output: %v", results)
	}
}
